import type { ComponentType } from 'react';

/** Every implementation the registry can measure. */
export type ImplementationName =
  | 'rn-core'
  | 'expo-ui-host-per-control'
  | 'expo-ui-shared-host'
  | 'nitro-ui'
  | 'nitro-ui-host';

/**
 * Which control a launch renders. `switch` was the only component until G1 and
 * keeps the bare scenario names (`mount`, `update`, …) so every results file,
 * baseline and `--compare` base recorded before then still lines up; from the
 * second component on, the component is part of the scenario cell
 * (`mount.slider`). See `docs/architecture/benchmarks.md`.
 */
export type ComponentName =
  // @generated by scripts/gen-registry.mjs (region: component-names) - do not edit; run bun run regen
  | 'switch'
  | 'slider'
  | 'button'
  | 'progress'
  | 'segmented-control'
  | 'date-picker'
  | 'picker';
// @end-generated

/** What one launch does to the controls. */
export type ScenarioAction = 'mount' | 'update' | 'memory' | 'leak';

/**
 * The cell name as it travels: on the launch argument, in every NDJSON record,
 * and in every results cell key. `parsePlan` splits it into `action` and
 * `component`, so nothing downstream has to know the encoding.
 */
export type ScenarioName =
  | ScenarioAction
  // @generated by scripts/gen-registry.mjs (region: scenario-names) - do not edit; run bun run regen
  | `${ScenarioAction}.slider`
  | `${ScenarioAction}.button`
  | `${ScenarioAction}.progress`
  | `${ScenarioAction}.segmented-control`
  | `${ScenarioAction}.date-picker`
  | `${ScenarioAction}.picker`;
// @end-generated

/**
 * A control set the harness can mount, update and unmount.
 *
 * `List` must render exactly `n` controls and must be safe to re-render with a
 * new `n` without remounting the wrapper (that is what makes `mount` measure
 * mounting `n` controls rather than remounting a subtree).
 */
export interface BenchImplementation {
  name: ImplementationName;
  /**
   * `false` means the component is not exported by the library yet, so the
   * runner skips it and says why instead of reporting a number nobody asked for.
   */
  available: boolean;
  skipReason: string | null;
  /**
   * Which controls this arm renders, or `null` for every component the plan has.
   *
   * An arm that implements one component (T16's `nitro-ui-host`, Switch only) must
   * not be launched on another component's cell: rendering nothing there would
   * still produce a plausible-looking mount time for zero controls. `BenchApp`
   * records a `skip` with the list instead, so the table says what was never
   * measured.
   */
  components: readonly ComponentName[] | null;
  List: ComponentType<BenchListProps>;
  /**
   * Turn on this runtime's *own* native perf marks, for a diagnostic run
   * (`bun bench --perf-marks`). Only `nitro-ui` has any: the library records
   * `propsApplied` / `firstFrame` per view when the view passes `nuiPerfId` and
   * `nitroUiCore.setPerfEnabled(true)` was called.
   *
   * Recording is a mutex-guarded ring write per mark and the drain is JS work,
   * so these exist for `--perf-marks` launches only - a measured run must not
   * call them, or the arm would pay for instrumentation no other arm pays.
   */
  enablePerfMarks: (() => void) | null;
  /**
   * Take every mark recorded since the last call (oldest first), in the probe's
   * nanosecond base (D1), or `null` when this runtime has no marks to give.
   */
  drainPerfMarks: (() => BenchPerfMark[] | null) | null;
}

export interface BenchListProps {
  /** Number of controls to render. `0` renders nothing. */
  n: number;
  /** The controlled value flipped by the `update` scenario. */
  value: boolean;
  /**
   * Which control to render.
   *
   * `value` stays a `boolean` for every component: the runner flips a bit and
   * each arm maps it onto that control's own value (`shared.ts`'s
   * `sliderValue`). Flipping a number instead would let one arm flip 0.25→0.75
   * while another flips 0→1, and the magnitude of a flip is not something arms
   * may differ on.
   */
  component: ComponentName;
  /**
   * Whether this launch wants native perf marks (`--perf-marks`). Only the
   * `nitro-ui` arm reads it: it tags instances with `nuiPerfId` so the library
   * records marks for them. `false` keeps the arm byte-identical in cost to the
   * reference arms.
   */
  perfMarks: boolean;
}

/**
 * Why one iteration produced no value for a latency signal.
 *
 * A missing sample used to be one bit - `null` - so a results file could say *how
 * many* presenting frames never arrived but never *why*, and the `n/a` that follows
 * refused a baseline with no evidence attached (A3's iOS mint: 105 of 160 samples
 * missing on one arm, cause undiagnosed). Every null now carries a code:
 *
 * - `'probe-timeout'` - the probe was asked and answered `-1` at the end of its
 *   timeout. The common case, and the only one whose meaning depends on how long the
 *   wait was, which is why `waitedMs` and `timeoutMs` travel with it.
 * - `'not-awaited'` - the cell declares `mountSignal: false`, so the runner never
 *   asked. The null is by construction rather than a lost signal, and without this
 *   code a per-cell summary would read those iterations as timeouts.
 * - `'probe-error'` - the call threw or answered unparseably. `detail` carries the
 *   message: unlike a timeout, this says the probe is broken, not that a frame was slow.
 */
export type MissingSampleReason =
  'probe-timeout' | 'not-awaited' | 'probe-error';

/**
 * One iteration's reason for one missing signal, compact enough to record on every
 * iteration of every launch.
 *
 * `kind`/`scenario`/`implementation`/`n`/`launch`/`index` are already on the `iter`
 * record this rides, so a reason is three short fields plus a timeout number - about
 * 40 bytes of NDJSON, and under 1 % on a full-plan results file.
 */
export interface MissingSample {
  /** Which signal did not arrive. */
  metric: 'mountedNs' | 'presentedNs';
  reason: MissingSampleReason;
  /** Wall-clock ms the runner actually waited, so a claimed timeout can be checked. */
  waitedMs: number;
  /** The timeout in force for this wait; null when nothing was waited. */
  timeoutMs: number | null;
  /** `probe-error` only: the message, clipped by the caller. */
  detail?: string;
}

/**
 * One native perf mark from the runtime under test, already converted to the
 * probe's nanosecond base so it lines up with `t0` (D1).
 */
export interface BenchPerfMark {
  /** The library's instance id (`nuiPerfId`). */
  instanceId: number;
  /** `'propsApplied'` (props landed on the UI thread) or `'firstFrame'`. */
  kind: string;
  /** Absolute timestamp, same base as `probe.now()`. */
  timeNs: number;
}

export interface BenchPlan {
  scenario: ScenarioName;
  /** `scenario` without its component suffix - what the launch does. */
  action: ScenarioAction;
  /** The control the launch renders. */
  component: ComponentName;
  implementation: ImplementationName;
  n: number;
  /**
   * `false` for a cell whose arm cannot produce the native transaction the probe
   * timestamps, so waiting for the mount/presented signals can only end in a
   * timeout. The runner then records both as `null` without waiting, and the
   * report says the pair is absent by construction rather than suspicious.
   * See `NO_MOUNT_SIGNAL` in `plan.ts`.
   */
  mountSignal: boolean;
  /**
   * `true` when the launch argument asked for native perf marks
   * (`scenario:implementation:N:marks`). Diagnostic only: it is not part of a
   * results cell key.
   */
  perfMarks: boolean;
  /**
   * How long this launch waits for the mount signal
   * (`scenario:implementation:N:mountTimeout=1500`, default 1500).
   */
  mountTimeoutMs: number;
  /**
   * How long this launch waits for the presenting frame
   * (`scenario:implementation:N:presentedTimeout=40000`, default 2000).
   *
   * Overridable per launch because the only way to tell "this arm never draws" from
   * "this arm draws slower than we wait" is to wait longer, and a release build has
   * no env to read - so it travels on the launch string like `marks` does. A run
   * that raises it is stamped in its results file and cannot mint a baseline: the
   * samples that arrive keep their values, but *which* samples arrive changes the
   * median, and a ratio is only comparable under one waiting rule.
   */
  presentedTimeoutMs: number;
}

/** One line of the NDJSON a launch writes. */
export type BenchRecord =
  | {
      kind: 'meta';
      scenario: ScenarioName;
      implementation: ImplementationName;
      n: number;
      launch: number;
      warmup: number;
      measured: number;
      /** Platform/os summary, so a results file is self-describing. */
      platform: string;
      probeClock: 'CLOCK_UPTIME_RAW' | 'System.nanoTime';
      /**
       * Echoed from the plan so a results file says whether this cell's latency
       * pair was ever measurable: `false` means the nulls in every `iter` record
       * are by construction, not a lost signal.
       */
      mountSignal: boolean;
      /**
       * What this launch waited for, so a `probe-timeout` reason in an `iter`
       * record can be checked against the rule that was in force. Written as
       * `timeout=<ms>` / `presentedTimeout=<ms>` flags on the launch string, so a
       * release build with no env can still be asked to wait longer (A4).
       */
      mountTimeoutMs: number;
      presentedTimeoutMs: number;
    }
  | {
      kind: 'iter';
      scenario: ScenarioName;
      implementation: ImplementationName;
      n: number;
      launch: number;
      index: number;
      warmup: boolean;
      /** null when the native signal never arrived. */
      jsCommitNs: number | null;
      mountedNs: number | null;
      presentedNs: number | null;
      /**
       * Why a null above is null, one entry per missing signal. Absent (not `[]`)
       * on the normal path, so every `iter` record in a healthy run stays the
       * size it was.
       */
      missing?: MissingSample[];
    }
  | {
      kind: 'cpu';
      scenario: ScenarioName;
      implementation: ImplementationName;
      n: number;
      launch: number;
      /**
       * Which part of the iteration the bracket covered. `mount` is the commit
       * plus the native mount only; `unmount` is the teardown that follows it.
       * They used to share one bracket, so "UI CPU/op" was really the cost of a
       * mount+teardown cycle (T02 review S5).
       */
      phase: 'mount' | 'unmount';
      iterations: number;
      /** CPU (not wall-clock) ns over the measured batch, divided later by `iterations`. */
      jsCpuNs: number | null;
      mainCpuNs: number | null;
    }
  | {
      /**
       * Written last, so a reader can tell a complete file from a partial one.
       */
      kind: 'end';
      scenario: ScenarioName;
      implementation: ImplementationName;
      n: number;
      launch: number;
      recordCount: number;
    }
  | {
      /**
       * The runtime's own native perf marks for one measured iteration, drained
       * between iterations (outside every CPU bracket) so the drain cannot
       * inflate a CPU metric. Emitted only by `--perf-marks` launches, reported
       * and never gated: this explains a `UI CPU/op` number, it is not a verdict.
       */
      kind: 'perf';
      scenario: ScenarioName;
      implementation: ImplementationName;
      n: number;
      launch: number;
      index: number;
      /** `propsApplied` marks (props landed on the UI thread) seen meanwhile. */
      propsApplied: number;
      /** `firstFrame` marks (the hosted content drew) seen meanwhile. */
      firstFrame: number;
      /** Distinct instance ids that reported anything. Expect `n`. */
      instances: number;
      /** Latest `propsApplied` after the iteration's `t0`; null when none. */
      propsAppliedNs: number | null;
      /** Latest `firstFrame` after the iteration's `t0`; null when none. */
      firstFrameNs: number | null;
      /** `firstFrame` minus `propsApplied` for the last instance to report. */
      drawLatencyNs: number | null;
    }
  | {
      kind: 'skip';
      scenario: ScenarioName;
      implementation: ImplementationName;
      n: number;
      launch: number;
      reason: string;
    }
  | {
      kind: 'mem';
      scenario: ScenarioName;
      implementation: ImplementationName;
      n: number;
      launch: number;
      /** `empty` | `full` | `leak0` ... `leakN` */
      phase: string;
      footprintBytes: number | null;
      /**
       * Whether a JS garbage collector was reachable before this sample.
       * Footprint includes the Hermes heap, so a sample without a collect is a
       * sample of whatever the GC happened to leave behind.
       */
      heapCollected: boolean;
      /** Android only: allocated native heap, or null. */
      nativeHeapBytes: number | null;
      /** Android only: used Java heap, or null. */
      javaHeapBytes: number | null;
    };
