'use strict';

/**
 * `react-native-nitro-ui/plugin` — the Expo config plugin for `androidIcon`.
 *
 * Android has no system icon set, so an app that uses `androidIcon` ships the
 * vectors itself (`docs/components/button.md`, "Android icons"). On a bare React
 * Native app that means dropping the files in `android/app/src/main/res/drawable/`
 * by hand; under Expo prebuild / CNG that folder is generated, so anything copied
 * into it by hand is gone at the next `prebuild --clean`. This plugin is the two
 * things CNG cannot know about:
 *
 *  1. it copies the app's `.xml` drawables into `res/drawable/`;
 *  2. it writes `res/raw/keep.xml` naming them, because the resource shrinker
 *     cannot see a name that arrives as a JavaScript string and would otherwise
 *     strip the icons out of a release build that sets `shrinkResources true`
 *     (or Expo's `enableShrinkResourcesInReleaseBuilds`).
 *
 * It is opt-in, and installing the library does not need it: an app that never
 * passes `androidIcon` has nothing to copy, and nothing here runs unless
 * `app.json` lists the plugin.
 *
 * ```json
 * { "plugins": [["react-native-nitro-ui/plugin", { "androidIcons": "./assets/android-icons" }]] }
 * ```
 *
 * `expo/config-plugins` is required lazily rather than at the top of the file. It
 * is the *app's* development dependency, not this package's, and the plugin is
 * only ever loaded by `expo prebuild`; a top-level require would make this file
 * unimportable everywhere else — including in `plugin/__tests__/plugin.test.js`,
 * which runs {@link applyAndroidIcons} against a fixture project with no Expo
 * installed. Same reason {@link applyAndroidIcons} is exported: a bare-RN
 * developer can run, and test, exactly what prebuild runs.
 */

const fs = require('node:fs');
const path = require('node:path');

/** What a resource may be called, per `aapt`. Mirrors `NitroUiIconNames` in Kotlin. */
const RESOURCE_NAME = /^[a-z][a-z0-9_]*$/;

/** The shrinker's keep file, under the app's `res/`. */
const KEEP_PATH = ['res', 'raw', 'keep.xml'];

/** The Android tools namespace, needed by `tools:keep`. */
const TOOLS_NS = 'http://schemas.android.com/tools';

/**
 * Marks the keep file as this plugin's, so a merge can tell "ours, again" from
 * "the app's own keep rules, which we must not overwrite".
 */
const KEEP_MARKER = 'react-native-nitro-ui/plugin';

/**
 * Copy {@link iconsDir}'s `.xml` drawables into the generated Android project and
 * write the keep file that protects them.
 *
 * Safe to run twice — which prebuild does, since `expo prebuild` and
 * `expo run:android` both apply mods: the copy overwrites identical bytes and the
 * keep file merges rather than appends, so a second run changes nothing.
 *
 * @param {object} options
 * @param {string} options.projectRoot the app project (`app.json`'s folder)
 * @param {string} options.platformProjectRoot the generated `android/` folder
 * @param {string | undefined} options.iconsDir the folder to copy, relative to `projectRoot`
 * @returns {{status: string, copied: string[], skipped: {name: string, why: string}[], keepPath: string | null, warnings: string[]}}
 */
function applyAndroidIcons(options) {
  const { projectRoot, platformProjectRoot, iconsDir } = options;
  const result = {
    status: 'skipped',
    copied: /** @type {string[]} */ ([]),
    skipped: /** @type {{name: string, why: string}[] */ ([]),
    keepPath: null,
    warnings: /** @type {string[]} */ ([]),
  };

  if (typeof iconsDir !== 'string' || iconsDir.length === 0) {
    result.status = 'no-androidIcons';
    return result;
  }

  const source = path.resolve(projectRoot, iconsDir);
  if (!fs.existsSync(source) || !fs.statSync(source).isDirectory()) {
    throw new Error(
      `react-native-nitro-ui/plugin: androidIcons "${iconsDir}" is not a folder ` +
        `(resolved to ${source}). Point it at the folder that holds your ` +
        `.xml vector drawables, relative to the project root.`
    );
  }

  const resDir = path.join(platformProjectRoot, 'app', 'src', 'main');
  if (!fs.existsSync(resDir)) {
    // Nothing to write into. The android project is generated by the time mods
    // run, so this is the "someone pointed the mod at a half-created tree" case,
    // and a warning beats a prebuild failure over a prop the app may not even use.
    result.status = 'no-android-project';
    result.warnings.push(
      `no Android app folder at ${resDir}; no icons were copied.`
    );
    return result;
  }

  const drawableDir = path.join(resDir, 'res', 'drawable');
  fs.mkdirSync(drawableDir, { recursive: true });

  for (const entry of fs.readdirSync(source).sort()) {
    if (!entry.toLowerCase().endsWith('.xml')) {
      continue;
    }
    const name = entry.slice(0, -'.xml'.length);
    if (!RESOURCE_NAME.test(name)) {
      // `aapt` rejects this file, so copying it would break the *build* rather
      // than just miss an icon — say so, and leave it out.
      result.skipped.push({
        name: entry,
        why:
          'is not a valid Android resource name: lower-case letters, digits and ' +
          'underscores only, and not starting with a digit',
      });
      continue;
    }
    const sourceFile = path.join(source, entry);
    if (!fs.statSync(sourceFile).isFile()) {
      continue;
    }
    const contents = fs.readFileSync(sourceFile, 'utf8');
    // The *root element*, not the text: a comment that mentions a vector is not
    // one, and this warning is only worth having if it does not also fire on
    // documentation.
    const rootElement = /<\s*([A-Za-z_-][\w.-]*)/.exec(
      contents.replace(/<!--[\s\S]*?-->/g, '')
    );
    if (rootElement == null || rootElement[1].toLowerCase() !== 'vector') {
      result.warnings.push(
        `${entry} is not a <vector> drawable, so a control may not be able to ` +
          `draw it as an icon (see docs/components/button.md, "Android icons").`
      );
    }
    fs.copyFileSync(sourceFile, path.join(drawableDir, entry));
    result.copied.push(name);
  }

  result.status = result.copied.length > 0 ? 'copied' : 'nothing-to-copy';
  if (result.copied.length > 0) {
    result.keepPath = writeKeepFile(resDir, result.copied);
  }
  return result;
}

/**
 * Write / merge `res/raw/keep.xml` so the shrinker keeps {@link names}.
 *
 * Merged rather than written because `keep.xml` is *one file per res folder* to
 * the shrinker: an app that already keeps something else (a font, a raw JSON)
 * would otherwise lose it the first time this plugin runs. Our entries go into
 * the same `tools:keep` attribute it would use by hand, sorted and de-duplicated
 * so the file is stable between prebuilds and its diff stays reviewable.
 */
function writeKeepFile(resDir, names) {
  const keepPath = path.join(resDir, ...KEEP_PATH);
  fs.mkdirSync(path.dirname(keepPath), { recursive: true });
  const ours = names.map((name) => `@drawable/${name}`).sort();

  if (!fs.existsSync(keepPath)) {
    fs.writeFileSync(
      keepPath,
      `<?xml version="1.0" encoding="utf-8"?>\n` +
        `<!-- Generated by ${KEEP_MARKER}.\n` +
        `     Names handed to nitro-ui's \`androidIcon\` arrive as JavaScript strings,\n` +
        `     which the resource shrinker cannot see, so it would strip them from a\n` +
        `     release build that shrinks resources. Edit by hand and the next prebuild\n` +
        `     keeps your entries - it merges. -->\n` +
        `<resources\n` +
        `  xmlns:tools="${TOOLS_NS}"\n` +
        `  tools:keep="${ours.join(',')}" />\n`,
      'utf8'
    );
    return keepPath;
  }

  const existing = fs.readFileSync(keepPath, 'utf8');
  const tag = /<resources\b[^>]*>/i.exec(existing);
  if (tag == null) {
    // Not a resources file we understand. Overwriting it would delete someone's
    // keep rules to protect an icon, which is the wrong trade.
    throw new Error(
      `react-native-nitro-ui/plugin: ${keepPath} has no <resources> element to ` +
        `add @drawable entries to. Add them by hand, or remove the file and ` +
        `prebuild again.`
    );
  }
  const attribute = /\stools:keep="([^"]*)"/i.exec(tag[0]);
  const hadNamespace = /\sxmlns:tools=/.test(tag[0]);
  let mergedTag = tag[0];
  if (attribute == null) {
    mergedTag = mergedTag.replace(
      />$/,
      `${hadNamespace ? '' : `\n  xmlns:tools="${TOOLS_NS}"`}\n  tools:keep="${ours.join(',')}">\n`
    );
  } else {
    /** @type {string[]} */
    const merged = [];
    for (const entry of `${attribute[1]},${ours.join(',')}`.split(',')) {
      const trimmed = entry.trim();
      if (trimmed.length > 0 && !merged.includes(trimmed)) {
        merged.push(trimmed);
      }
    }
    merged.sort();
    mergedTag = mergedTag.replace(
      attribute[0],
      ` tools:keep="${merged.join(',')}"`
    );
  }
  const mergedFile = existing.replace(tag[0], mergedTag);
  if (mergedFile !== existing) {
    fs.writeFileSync(keepPath, mergedFile, 'utf8');
  }
  return keepPath;
}

/**
 * The Expo config plugin itself.
 *
 * `withDangerousMod` is the right mod, not a fallback: this writes files inside
 * the generated Android project that no other mod knows about, which is exactly
 * what that mod exists for, and it runs after the project is generated.
 */
function withNitroUiAndroidIcons(config, props) {
  // See the file header for why this is here rather than at the top.
  const { withDangerousMod } = require('expo/config-plugins');
  const iconsDir = props == null ? undefined : props.androidIcons;
  return withDangerousMod(config, [
    'android',
    (modConfig) => {
      const request = modConfig.modRequest;
      const projectRoot = request == null ? process.cwd() : request.projectRoot;
      const platformProjectRoot =
        request == null
          ? path.join(projectRoot, 'android')
          : request.platformProjectRoot;
      const result = applyAndroidIcons({
        projectRoot,
        platformProjectRoot,
        iconsDir,
      });
      for (const warning of result.warnings) {
        console.warn(`nitro-ui/plugin: ${warning}`);
      }
      for (const skipped of result.skipped) {
        console.warn(
          `nitro-ui/plugin: skipped ${skipped.name} - it ${skipped.why}.`
        );
      }
      if (result.copied.length > 0) {
        console.log(
          `nitro-ui/plugin: copied ${String(result.copied.length)} Android ` +
            `icon(s) into res/drawable and named them in ` +
            `res/raw/keep.xml (${result.copied.join(', ')}).`
        );
      }
      return modConfig;
    },
  ]);
}

module.exports = withNitroUiAndroidIcons;
module.exports.default = withNitroUiAndroidIcons;
module.exports.withNitroUiAndroidIcons = withNitroUiAndroidIcons;
module.exports.applyAndroidIcons = applyAndroidIcons;
