/**
 * The deciding half of `scripts/task-ready.mjs` — the checks that need no git and no
 * subprocess, so they can be unit-tested and shown red.
 *
 * See `task-ready.mjs` for what the command is for and why each check is in the list.
 *
 * @file No `import.meta`, no `node:child_process`: the same reason `gate-core.mjs`,
 *       `lease-core.mjs` and `registry-core.mjs` all give in their headers — those
 *       files say that `import.meta` makes a module unimportable from a Jest suite,
 *       and `scripts/__tests__/task-ready.test.js` imports this one.
 */

/**
 * The four rules' home, so the TODO scan can say what a hit *means*.
 *
 * A `TODO` in a hand-written file is a note; a `TODO` in a declared fallback or inside a
 * generated region is a promise the generator will silently overwrite, or a fallback that
 * was never decided. Those two cases are what this looks for, and only those.
 */
const GENERATED_MARKER = /@generated by scripts\/gen-registry\.mjs/;
const GENERATED_END = '@end-generated';
const FALLBACK_FILE = /DeclaredFallbacks\.(kt|swift|ts|tsx)$/;

/**
 * `TODO` / `FIXME` in a declared-fallback file or inside a generated region.
 *
 * Generated regions are found by the marker `registry-core.mjs` writes, not by line
 * ranges: a region's position moves whenever a control is added, and a check that tracked
 * offsets would silently scan the wrong lines. The anchored regions (`nitro.json`, the two
 * declared-fallback tables) have no marker, so those files are covered by name — which is
 * also the more honest rule: nobody hand-writes a fallback anywhere else.
 *
 * @param {Map<string, string> | Array<[string, string]>} files path → text, of the files
 *   the branch touched. Passing only the diff's files is deliberate: a legacy `TODO` in a
 *   file nobody is editing is not this round's problem, and a check that reports it teaches
 *   people to run the tool with `--no-verify`.
 * @returns {string[]} one line per hit, `path:line: text`
 */
export function todoFindings(files) {
  const problems = [];
  for (const [path, text] of files) {
    const lines = text.split('\n');
    let insideGenerated = false;
    lines.forEach((line, index) => {
      if (GENERATED_MARKER.test(line)) insideGenerated = true;
      else if (line.includes(GENERATED_END)) insideGenerated = false;
      const inFallback = FALLBACK_FILE.test(path);
      if (!insideGenerated && !inFallback) return;
      if (!/\b(TODO|FIXME)\b/.test(line)) return;
      problems.push(
        `${path}:${String(index + 1)}: ${line.trim()} — a ${
          inFallback ? 'declared fallback' : 'generated region'
        } with a ${/\bFIXME\b/.test(line) ? 'FIXME' : 'TODO'} is a decision ` +
          (inFallback
            ? 'nobody made; the engine lays this control out at whatever ' +
              'number is here'
            : 'the generator will overwrite the next time anyone runs `regen`')
      );
    });
  }
  return problems;
}

/**
 * Backticked repo paths in a report that do not exist at HEAD.
 *
 * X3's first report cited files that were never in the tree, and a citation a reviewer
 * cannot open is worth less than no citation. Two rules make this usable rather than
 * noise:
 *
 * - only a backtick whose whole content is a repo-shaped path is considered, and repo-shaped
 *   means it contains a `/`. `nitro-ui.sizing.json` is a real file and a report may cite it,
 *   but so are `REPORT-TEMPLATE.md` and `package.json` — a bare name cannot be resolved to a
 *   directory without guessing, and a check that guesses reports half the prose in every
 *   report as broken. Requiring a directory keeps the signal in the invented paths a reviewer
 *   actually goes to read.
 * - a path the branch's own diff adds or deletes is allowed, since the report is describing
 *   work in this branch.
 *
 * @param {string} reportText the text of `docs/tasks/<ID>.report.md`
 * @param {Set<string>} existing paths that exist at HEAD
 * @param {Set<string>} [touched] paths the branch's diff adds, deletes or modifies
 * @returns {string[]} problems
 */
export function missingReportPaths(reportText, existing, touched = new Set()) {
  const problems = [];
  const seen = new Set();
  for (const match of reportText.matchAll(/`([^`\n]+)`/g)) {
    const cited = match[1].trim();
    if (!isRepoPath(cited)) continue;
    // Deduped on the path, not on the citation: `path.mjs` and `path.mjs:12` are one
    // citation of one file, and a report that mentions a bad path five times with five
    // different line ranges has one problem to fix.
    const path = cited.replace(/:\d+(?:-\d+)?$/, '');
    if (seen.has(path)) continue;
    seen.add(path);
    if (existing.has(path) || touched.has(path)) continue;
    problems.push(
      `report cites \`${cited}\` and nothing at HEAD has that path, and ` +
        "the branch's diff neither adds nor deletes it — a citation a reviewer " +
        'cannot open reads as evidence and is not'
    );
  }
  return problems;
}

/**
 * Is this backtick content a repo path rather than a symbol, a script name or prose?
 *
 * Conservative on purpose. A path has to contain a `/`, which is what distinguishes
 * `example/src/App.tsx` from `App.tsx`, `test:native`, `hybridRef` or `fillWidth` — and the
 * bare-name cases are not the failure mode: an invented `Foo.kt` in a report is invisible
 * either way, while an invented directory-qualified path is the thing a reviewer goes to
 * read and cannot find.
 *
 * A trailing line citation (`path.tsx:12-20`, the repo's own citation shape) is stripped
 * first, since it is a citation *of* a path.
 *
 * @param {string} cited the whole content of one backtick pair
 */
export function isRepoPath(cited) {
  if (cited.includes(' ') || cited.length === 0) return false;
  if (/^(https?:|@|https\/\/)/.test(cited)) return false;
  const path = cited.replace(/:\d+(?:-\d+)?$/, '');
  // No absolute paths and no `..`: a report cites the repo by its own layout, and a path
  // outside it is somebody's local machine, which `existing` can never contain.
  if (!path.includes('/') || path.startsWith('/')) return false;
  if (path.startsWith('~') || path.split('/').includes('..')) return false;
  return /^[\w.@-]+(\/[\w.@-]+)+$/.test(path);
}

/**
 * The report's own gate table, as the lines `gate.mjs table` prints.
 *
 * Compared against the freshly generated table so a report cannot keep claiming a gate
 * passed on a tree the report no longer describes. Only the `| Gate |` rows are compared:
 * a report is prose around the table, and pasting is allowed to be wrapped.
 *
 * @param {string} reportText
 * @param {string[]} generatedTable the lines `gate.mjs table` printed
 * @returns {string[]} problems
 */
export function reportTableProblems(reportText, generatedTable) {
  const inReport = reportRows(reportText);
  const generated = reportRows(generatedTable.join('\n'));
  if (generated.length === 0) {
    // Nothing recorded yet, so there is nothing to match: the `need` check already
    // refuses a round with no gates, and this one must not double-report it.
    return [];
  }
  if (inReport.length === 0) {
    return [
      'the report has no gate table, and `gate.mjs table` has one — paste ' +
        'the generated rows rather than typing results',
    ];
  }
  const problems = [];
  for (const row of generated) {
    if (inReport.includes(row)) continue;
    const gate = row.split('|')[1]?.trim() ?? row;
    const stale = inReport.find(
      (line) => (line.split('|')[1]?.trim() ?? '') === gate
    );
    problems.push(
      stale == null
        ? `the report's gate table has no row for \`${gate}\`, which ` +
            '`gate.mjs table` prints for this code tree'
        : `the report's row for \`${gate}\` does not match what ` +
            '`gate.mjs table` prints now — ' +
            `report says ${stale.trim()} and the ledger says ${row.trim()}. ` +
            'A stale row is a claim; the ledger row is evidence'
    );
  }
  return problems;
}

/**
 * The `| Gate | ... |` data rows of a markdown table.
 *
 * @param {string} text
 */
function reportRows(text) {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^\|\s*[^|-][^|]*\|.*\|\s*$/.test(line))
    .filter((line) => !/^\|\s*-{3,}/.test(line))
    .filter((line) => !/^\|\s*Gate\s*\|/i.test(line));
}

/**
 * Which report file a task id and a branch name refer to.
 *
 * AGENTS.md says the report is `docs/tasks/<ID>.report.md`, and `gate.mjs export --task <ID>`
 * writes its ledger to `docs/tasks/<ID>/gates.jsonl` — both keyed on the orchestrator's id.
 * But a branch is named for the *task*, not the id: X4's brief is `X4-conformance.md`, so its
 * branch is `task/X4-conformance` and the natural report name is
 * `docs/tasks/X4-conformance.report.md`, next to its own brief.
 *
 * Rather than pick one spelling and make the other a hard error, the command accepts either
 * and looks for both. What it will not do is run the report checks against a file that does
 * not exist, so it names the candidates it looked for.
 *
 * @param {string | null} id the orchestrator's task id (`X4`)
 * @param {string | null} branch the branch suffix (`X4-conformance`), or null
 * @returns {string[]} report paths to look for, in priority order
 */
export function reportCandidates(id, branch) {
  const names = [];
  if (branch != null && branch !== '') names.push(branch);
  if (id != null && id !== '' && !names.includes(id)) names.push(id);
  return names.map((name) => `docs/tasks/${name}.report.md`);
}

/**
 * Summarise the checks into the lines and exit code the command prints.
 *
 * Kept separate from the checks so a test can assert "these findings, these lines, this
 * code" without a git repository or a gate ledger.
 *
 * @param {Record<string, string[]>} sections name → problems
 * @returns {{lines: string[], ok: boolean}}
 */
export function summarise(sections) {
  const lines = [];
  let ok = true;
  for (const [name, problems] of Object.entries(sections)) {
    if (problems.length === 0) {
      lines.push(`  ok    ${name}`);
      continue;
    }
    ok = false;
    lines.push(`  ${String(problems.length)} problem(s)  ${name}`);
    for (const problem of problems) lines.push(`          - ${problem}`);
  }
  return { lines, ok };
}
