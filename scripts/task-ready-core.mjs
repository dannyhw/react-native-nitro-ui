/**
 * The checks behind `scripts/task-ready.mjs` that need no git and no subprocess.
 * No `import.meta` here: it would make the module unimportable from Jest.
 */

/** The marker `registry-core.mjs` writes at the start of a generated region. */
const GENERATED_MARKER = /@generated by scripts\/gen-registry\.mjs/;
const GENERATED_END = '@end-generated';
const FALLBACK_FILE = /DeclaredFallbacks\.(kt|swift|ts|tsx)$/;

/**
 * A test file. The "near a fallback declaration" rule skips these: fixtures hold
 * component sources in miniature, and a test file ships no fallback.
 */
const TEST_FILE = /(^|\/)__tests__(\/|$)|\.(test|spec)\.[cm]?[jt]sx?$/;

/** A line that declares a fallback size (`fallbackSize` in Swift, `FALLBACK_*_DP` in Kotlin). */
const FALLBACK_DECLARATION =
  /\b(?:fallbackSize|FALLBACK_[A-Z0-9_]*_DP)\b\s*(?::\s*[\w.]+\s*)?=/;

/** How many lines from a fallback declaration a `TODO` may be and still be about it. */
const FALLBACK_CONTEXT_LINES = 2;

/**
 * `TODO` / `FIXME` in a declared-fallback file, inside a generated region, or
 * next to a fallback declaration.
 *
 * @param {Map<string, string> | Array<[string, string]>} files path → text, of the files
 *   the branch touched
 * @returns {string[]} one line per hit, `path:line: text`
 */
export function todoFindings(files) {
  const problems = [];
  for (const [path, text] of files) {
    const lines = text.split('\n');
    const inFallback = FALLBACK_FILE.test(path);
    const declared =
      inFallback || TEST_FILE.test(path) ? [] : fallbackDeclarationLines(lines);
    let insideGenerated = false;
    lines.forEach((line, index) => {
      if (GENERATED_MARKER.test(line)) insideGenerated = true;
      else if (line.includes(GENERATED_END)) insideGenerated = false;
      const nearFallback =
        inFallback ||
        declared.some((at) => Math.abs(at - index) <= FALLBACK_CONTEXT_LINES);
      if (!insideGenerated && !nearFallback) return;
      if (!/\b(TODO|FIXME)\b/.test(line)) return;
      const marker = /\bFIXME\b/.test(line) ? 'FIXME' : 'TODO';
      // A hit inside a generated region is reported as that even when the file
      // also declares a fallback.
      const about = insideGenerated
        ? 'a generated region'
        : inFallback
          ? 'a declared fallback'
          : 'a fallback number';
      const why = insideGenerated
        ? 'is a decision the generator will overwrite the next time anyone ' +
          'runs `regen`'
        : 'is a decision nobody made; the engine lays this control out at ' +
          'whatever number is here';
      problems.push(
        `${path}:${String(index + 1)}: ${line.trim()} — ${about} with a ${marker} ${why}`
      );
    });
  }
  return problems;
}

/**
 * Which lines of a file declare a fallback size.
 *
 * @param {string[]} lines
 * @returns {number[]} 0-based line numbers
 */
function fallbackDeclarationLines(lines) {
  const found = [];
  lines.forEach((line, index) => {
    if (FALLBACK_DECLARATION.test(line)) found.push(index);
  });
  return found;
}

/**
 * Backticked repo paths in a report that do not exist at HEAD. A path the branch's
 * own diff adds or deletes is allowed.
 *
 * @param {string} reportText the report's text
 * @param {Set<string>} existing paths that exist at HEAD
 * @param {Set<string>} [touched] paths the branch's diff adds, deletes or modifies
 * @returns {string[]} problems
 */
export function missingReportPaths(reportText, existing, touched = new Set()) {
  const problems = [];
  const seen = new Set();
  for (const match of reportText.matchAll(/`([^`\n]+)`/g)) {
    const cited = match[1].trim();
    if (!isRepoPath(cited)) continue;
    // Deduped on the path: `path.mjs` and `path.mjs:12` cite one file.
    const path = cited.replace(/:\d+(?:-\d+)?$/, '');
    if (seen.has(path)) continue;
    seen.add(path);
    if (existing.has(path) || touched.has(path)) continue;
    problems.push(
      `report cites \`${cited}\` and nothing at HEAD has that path, and ` +
        "the branch's diff neither adds nor deletes it — a citation a reviewer " +
        'cannot open reads as evidence and is not'
    );
  }
  return problems;
}

/**
 * The problem a check reports when it could not look, so "nothing found" cannot
 * read as "nothing wrong".
 *
 * @param {string} what the thing that could not be read, e.g. "the TODO scan"
 * @param {string} why why not, e.g. "no merge-base with `main`"
 * @param {string} [fix] what to do about it, when a caller can
 * @returns {string[]} exactly one problem
 */
export function unscannedProblem(what, why, fix) {
  return [
    `${why}, so ${what} could not run and checked nothing — its silence ` +
      'means "nothing to look at", not "nothing wrong", and this tool reports those ' +
      'differently on purpose' +
      (fix == null ? '.' : `. ${fix}`),
  ];
}

/**
 * Is this backtick content a repo path? It must contain a `/` and its last segment
 * must have an extension, which keeps branch names out. A trailing line citation
 * (`path.tsx:12-20`) is stripped first.
 *
 * @param {string} cited the whole content of one backtick pair
 */
export function isRepoPath(cited) {
  if (cited.includes(' ') || cited.length === 0) return false;
  if (/^(https?:|@|https\/\/)/.test(cited)) return false;
  const path = cited.replace(/:\d+(?:-\d+)?$/, '');
  // No absolute paths and no `..`: a report cites the repo by its own layout.
  if (!path.includes('/') || path.startsWith('/')) return false;
  if (path.startsWith('~') || path.split('/').includes('..')) return false;
  if (!/^[\w.@-]+(\/[\w.@-]+)+$/.test(path)) return false;
  const leaf = path.slice(path.lastIndexOf('/') + 1);
  return leaf.includes('.') && !leaf.startsWith('.');
}

/**
 * The report's own gate table, against the lines `gate.mjs table` prints. Only table
 * rows are compared, with inline-code markup stripped from the ends of cells.
 *
 * @param {string} reportText
 * @param {string[]} generatedTable the lines `gate.mjs table` printed
 * @returns {string[]} problems
 */
export function reportTableProblems(reportText, generatedTable) {
  const inReport = reportRows(reportText);
  const generated = reportRows(generatedTable.join('\n'));
  if (generated.length === 0) {
    // Nothing recorded yet, so there is nothing to match.
    return [];
  }
  if (inReport.length === 0) {
    return [
      'the report has no gate table, and `gate.mjs table` has one — paste ' +
        'the generated rows rather than typing results',
    ];
  }
  const problems = [];
  for (const row of generated) {
    if (inReport.some((line) => sameRow(line, row))) continue;
    const gate = unwrapGate(row.split('|')[1]?.trim() ?? row);
    const stale = inReport.find(
      (line) => unwrapGate(line.split('|')[1]?.trim() ?? '') === gate
    );
    problems.push(
      stale == null
        ? `the report's gate table has no row for \`${gate}\`, which ` +
            '`gate.mjs table` prints for this code tree'
        : `the report's row for \`${gate}\` does not match what ` +
            '`gate.mjs table` prints now — ' +
            `report says ${stale.trim()} and the ledger says ${row.trim()}. ` +
            'A stale row is a claim; the ledger row is evidence'
    );
  }

  // The other direction: a row that claims a result for a gate must be exactly a
  // row the ledger printed. A claim is a row whose first cell is gate-shaped and
  // whose second is verdict-shaped; a report's other tables are left alone.
  const known = new Set(generated.map((line) => gateNameOf(line) ?? ''));
  /** Gate names the report has the ledger's own row for, correctly. */
  const faithful = new Set(
    generated
      .map((line) => gateNameOf(line))
      .filter((gate) => gate != null)
      .filter((gate) =>
        generated.some(
          (line) =>
            gateNameOf(line) === gate &&
            inReport.some((row) => sameRow(row, line))
        )
      )
  );
  const claims = new Map();
  /** Gates already named by a problem below, so the count check does not say it twice. */
  const reported = new Set();
  for (const row of inReport) {
    const gate = gateNameOf(row);
    if (gate == null) continue;
    claims.set(gate, (claims.get(gate) ?? 0) + 1);
    if (generated.some((line) => sameRow(line, row))) continue;
    if (known.has(gate) && !faithful.has(gate)) continue;
    reported.add(gate);
    problems.push(
      faithful.has(gate)
        ? `the report's gate table carries a second row for \`${gate}\` that ` +
            '`gate.mjs table` does not print, so no run of it looks like that — ' +
            `the row says ${row.trim()}. A gate appears once, with the ledger's own ` +
            'numbers: an extra row beside a correct one is as invented as one for a ' +
            'gate that never ran'
        : `the report's gate table has a row for \`${gate}\` and ` +
            '`gate.mjs table` prints none, so no run of that gate is recorded for this ' +
            `code tree — the row says ${row.trim()}. Paste the table, do not extend it`
    );
  }
  // A gate named twice reads as two runs, even when every copy matches the
  // ledger's row.
  for (const [gate, count] of claims) {
    if (count < 2 || reported.has(gate)) continue;
    problems.push(
      `the report's gate table lists \`${gate}\` ${String(count)} times and ` +
        '`gate.mjs table` records one run of it — a gate named twice reads as two runs, ' +
        'and the ledger says there is one'
    );
  }
  return problems;
}

/**
 * The gate a table row claims a result for, or null when it claims none.
 *
 * @param {string} row one markdown data row
 * @returns {string | null}
 */
function gateNameOf(row) {
  const cells = tableCells(row);
  if (cells.length < 2) return null;
  if (!/^[a-z][a-z0-9-]*(?::[A-Za-z0-9-]+)*$/.test(cells[0])) return null;
  if (
    !/^\*{0,2}(PASS|FAIL|green|red|stale|skipped|pending|missing|not run)\*{0,2}$/i.test(
      cells[1]
    )
  )
    return null;
  return cells[0];
}

/**
 * A markdown row's cells, trimmed and with the markup that only decorates them removed.
 *
 * @param {string} row
 * @returns {string[]}
 */
function tableCells(row) {
  return row
    .split('|')
    .map((cell) => cell.trim().replace(/^`+|`+$/g, ''))
    .filter((cell) => cell !== '');
}

/**
 * Shorthand groups for `--only`. An unknown name comes back unchanged, so the
 * caller's unknown-name check still fires.
 *
 * @type {Readonly<Record<string, ReadonlyArray<string>>>}
 */
export const ONLY_GROUPS = Object.freeze({
  report: Object.freeze(['report-paths', 'report-table']),
});

/**
 * @param {ReadonlyArray<string>} names as typed, comma-split and trimmed
 * @returns {string[]} every group replaced by its members, in order
 */
export function expandOnly(names) {
  return names.flatMap((name) => [...(ONLY_GROUPS[name] ?? [name])]);
}

/**
 * Are these two table rows the same row, ignoring inline code markup?
 *
 * @param {string} a
 * @param {string} b
 * @returns {boolean}
 */
function sameRow(a, b) {
  const left = tableCells(a);
  const right = tableCells(b);
  return left.length === right.length && left.every((c, i) => c === right[i]);
}

/**
 * The gate name out of a table cell, without the backticks around it.
 *
 * @param {string} cell
 * @returns {string}
 */
function unwrapGate(cell) {
  return cell.replace(/^`+|`+$/g, '');
}

/**
 * The `| Gate | ... |` data rows of a markdown table.
 *
 * @param {string} text
 */
function reportRows(text) {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^\|\s*[^|-][^|]*\|.*\|\s*$/.test(line))
    .filter((line) => !/^\|\s*-{3,}/.test(line))
    .filter((line) => !/^\|\s*Gate\s*\|/i.test(line));
}

/**
 * The task a branch belongs to, read off the branch name. Any `prefix/suffix`
 * collapses to its suffix, and an id must contain a digit, so a prose branch
 * name (`main`) names no task.
 *
 * @param {string | null | undefined} branchRef `task/X4-conformance`,
 *   `refs/heads/merge/X4`, `HEAD`, or null
 * @returns {{branch: string | null, id: string | null}} the branch suffix (what a
 *   branch-named report is called after) and the task id, either null
 */
export function taskFromBranchName(branchRef) {
  const ref = String(branchRef ?? '').trim();
  if (ref === '' || ref === 'HEAD') return { branch: null, id: null };
  const name = ref.replace(/^refs\/(?:heads|remotes)\//, '');
  const slash = name.indexOf('/');
  const branch =
    slash === -1 ? name : name.slice(slash + 1).replace(/^\/+/, '');
  const suffix = branch === '' ? null : branch;
  return { branch: suffix, id: taskIdFromBranch(suffix) };
}

/**
 * The task ids at the head of a branch suffix: none for a prose name, one for
 * `X4-conformance` or `X29-fix2`, two for a merge branch such as `G25-G26-merge`.
 * An id is an uppercase prefix plus digits.
 *
 * @param {string | null | undefined} branch
 * @returns {string[]} the ids at the head of the name, empty when there is none
 */
export function taskIdsFromBranch(branch) {
  const tokens = String(branch ?? '')
    .trim()
    .split(/[-._]/);
  const leading = tokens[0];
  if (leading == null || leading === '' || !/\d/.test(leading)) return [];
  const ids = [leading];
  if (/^[A-Z]{1,4}\d{1,3}$/.test(tokens[1] ?? '')) ids.push(tokens[1]);
  return ids;
}

/**
 * The one task a branch belongs to, or null when the branch does not name exactly
 * one: `X4-conformance` -> `X4`, `G25-G26-merge` -> null.
 *
 * @param {string | null | undefined} branch
 * @returns {string | null}
 */
export function taskIdFromBranch(branch) {
  const ids = taskIdsFromBranch(branch);
  return ids.length === 1 ? ids[0] : null;
}

/**
 * The report files a task id and a branch name may refer to, in priority order:
 * `<branch>.report.md`, `<ID>.report.md`, then `<ID>-*.report.md` when exactly
 * one file matches. Several slug matches are not offered, because choosing
 * between two reports is a guess.
 *
 * @param {string | null} id the task id (`X4`)
 * @param {string | null} branch the branch suffix (`X4-conformance`), or null
 * @param {string[]} [taskFiles] the file names in the tasks directory (basenames
 *   or paths); without it only the first two spellings are offered
 * @returns {string[]} report paths to look for, in priority order
 */
export function reportCandidates(id, branch, taskFiles = []) {
  const names = [];
  if (branch != null && branch !== '') names.push(branch);
  if (id != null && id !== '' && !names.includes(id)) names.push(id);
  const paths = names.map((name) => `docs/tasks/${name}.report.md`);
  const slugs = slugReportNames(id, taskFiles);
  if (slugs.length === 1) {
    const only = `docs/tasks/${slugs[0]}`;
    if (!paths.includes(only)) paths.push(only);
  }
  return paths;
}

/**
 * The `<ID>-*.report.md` files in a listing of the tasks directory, sorted. A
 * brief (`<ID>-<slug>.md`) never matches.
 *
 * @param {string | null} id the task id (`X4`)
 * @param {Iterable<string> | null} [taskFiles] names in the tasks directory; empty when unknown
 * @returns {string[]} the matching report file names, basenames, sorted
 */
export function slugReportNames(id, taskFiles = []) {
  if (id == null || id === '' || taskFiles == null) return [];
  const prefix = `${id}-`;
  const seen = new Set();
  for (const entry of taskFiles) {
    const name = String(entry).split('/').pop();
    if (
      name.length > prefix.length + '.report.md'.length &&
      name.startsWith(prefix) &&
      name.endsWith('.report.md')
    ) {
      seen.add(name);
    }
  }
  return [...seen].sort();
}

/**
 * Summarises the checks into the lines the command prints.
 *
 * @param {Record<string, string[]>} sections name → problems
 * @returns {{lines: string[], ok: boolean}}
 */
export function summarise(sections) {
  const lines = [];
  let ok = true;
  for (const [name, problems] of Object.entries(sections)) {
    if (problems.length === 0) {
      lines.push(`  ok    ${name}`);
      continue;
    }
    ok = false;
    lines.push(`  ${String(problems.length)} problem(s)  ${name}`);
    for (const problem of problems) lines.push(`          - ${problem}`);
  }
  return { lines, ok };
}
