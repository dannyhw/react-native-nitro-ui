/**
 * The deciding half of `scripts/task-ready.mjs` — the checks that need no git and no
 * subprocess, so they can be unit-tested and shown red.
 *
 * See `task-ready.mjs` for what the command is for and why each check is in the list.
 *
 * @file No `import.meta`, no `node:child_process`: the same reason `gate-core.mjs`,
 *       `lease-core.mjs` and `registry-core.mjs` all give in their headers — those
 *       files say that `import.meta` makes a module unimportable from a Jest suite,
 *       and `scripts/__tests__/task-ready.test.js` imports this one.
 */

/**
 * The four rules' home, so the TODO scan can say what a hit *means*.
 *
 * A `TODO` in a hand-written file is a note; a `TODO` in a declared fallback or inside a
 * generated region is a promise the generator will silently overwrite, or a fallback that
 * was never decided. Those two cases are what this looks for, and only those.
 */
const GENERATED_MARKER = /@generated by scripts\/gen-registry\.mjs/;
const GENERATED_END = '@end-generated';
const FALLBACK_FILE = /DeclaredFallbacks\.(kt|swift|ts|tsx)$/;

/**
 * A line that *declares* a fallback size, wherever it lives.
 *
 * The review's N2: the number each control falls back to is written in the component's own
 * source (`fallbackSize` in Swift, `FALLBACK_WIDTH_DP` in Kotlin), and the generated
 * `DeclaredFallbacks` tables are made from it — so a `TODO` beside one of those declarations
 * is exactly the undecided fallback the check exists to catch, and it used to be scanned as
 * ordinary hand-written code. `ios/components/Switch/HybridNitroUiSwitch.swift` and its five
 * siblings, plus `android/src/main/java/…/HybridNitroUi*.kt`, are where the answer lives.
 *
 * Matched on the declaration rather than on the filename, because those files are ordinary
 * 1 300-line component sources that carry legitimate notes: the rule stays "a `TODO` about a
 * fallback number", and the window below is what keeps it from reporting every note in the
 * file.
 */
const FALLBACK_DECLARATION =
  /\b(?:fallbackSize|FALLBACK_[A-Z0-9_]*_DP)\b\s*(?::\s*[\w.]+\s*)?=/;

/**
 * How close to a fallback declaration a `TODO` has to be to be about it.
 *
 * Two lines: the comment above the constant and the line below it are where somebody writes
 * "measure on iPad" or "matches Compose's touch target". Further away, and a note is about
 * the control rather than about the number, which is the case the check has always left
 * alone.
 */
const FALLBACK_CONTEXT_LINES = 2;

/**
 * `TODO` / `FIXME` in a declared-fallback file or inside a generated region.
 *
 * Generated regions are found by the marker `registry-core.mjs` writes, not by line
 * ranges: a region's position moves whenever a control is added, and a check that tracked
 * offsets would silently scan the wrong lines. The anchored regions (`nitro.json`, the two
 * declared-fallback tables) have no marker, so those files are covered by name — which is
 * also the more honest rule: nobody hand-writes a fallback anywhere else.
 *
 * A file that is not a fallback table still gets one look: the lines around a fallback
 * declaration ({@link FALLBACK_DECLARATION}), which is where the number this repo argues
 * about is actually written.
 *
 * @param {Map<string, string> | Array<[string, string]>} files path → text, of the files
 *   the branch touched. Passing only the diff's files is deliberate: a legacy `TODO` in a
 *   file nobody is editing is not this round's problem, and a check that reports it teaches
 *   people to run the tool with `--no-verify`.
 * @returns {string[]} one line per hit, `path:line: text`
 */
export function todoFindings(files) {
  const problems = [];
  for (const [path, text] of files) {
    const lines = text.split('\n');
    const inFallback = FALLBACK_FILE.test(path);
    const declared = inFallback ? [] : fallbackDeclarationLines(lines);
    let insideGenerated = false;
    lines.forEach((line, index) => {
      if (GENERATED_MARKER.test(line)) insideGenerated = true;
      else if (line.includes(GENERATED_END)) insideGenerated = false;
      const nearFallback =
        inFallback || declared.some((at) => Math.abs(at - index) <= FALLBACK_CONTEXT_LINES);
      if (!insideGenerated && !nearFallback) return;
      if (!/\b(TODO|FIXME)\b/.test(line)) return;
      const marker = /\bFIXME\b/.test(line) ? 'FIXME' : 'TODO';
      // Which of the three things this hit is, in the order the scan found them. A note
      // inside a generated region is the generator's problem even when the file also
      // declares a fallback, so that branch comes first.
      const about = insideGenerated
        ? 'a generated region'
        : inFallback
          ? 'a declared fallback'
          : 'a fallback number';
      const why = insideGenerated
        ? 'is a decision the generator will overwrite the next time anyone ' +
          'runs `regen`'
        : 'is a decision nobody made; the engine lays this control out at ' +
          'whatever number is here';
      problems.push(
        `${path}:${String(index + 1)}: ${line.trim()} — ${about} with a ${marker} ${why}`
      );
    });
  }
  return problems;
}

/**
 * Which lines of a file declare a fallback size.
 *
 * @param {string[]} lines
 * @returns {number[]} 0-based line numbers
 */
function fallbackDeclarationLines(lines) {
  const found = [];
  lines.forEach((line, index) => {
    if (FALLBACK_DECLARATION.test(line)) found.push(index);
  });
  return found;
}

/**
 * Backticked repo paths in a report that do not exist at HEAD.
 *
 * X3's first report cited files that were never in the tree, and a citation a reviewer
 * cannot open is worth less than no citation. Two rules make this usable rather than
 * noise:
 *
 * - only a backtick whose whole content is a repo-shaped path is considered, and repo-shaped
 *   means it contains a `/`. `nitro-ui.sizing.json` is a real file and a report may cite it,
 *   but so are `REPORT-TEMPLATE.md` and `package.json` — a bare name cannot be resolved to a
 *   directory without guessing, and a check that guesses reports half the prose in every
 *   report as broken. Requiring a directory keeps the signal in the invented paths a reviewer
 *   actually goes to read.
 * - a path the branch's own diff adds or deletes is allowed, since the report is describing
 *   work in this branch.
 *
 * @param {string} reportText the text of `docs/tasks/<ID>.report.md`
 * @param {Set<string>} existing paths that exist at HEAD
 * @param {Set<string>} [touched] paths the branch's diff adds, deletes or modifies
 * @returns {string[]} problems
 */
export function missingReportPaths(reportText, existing, touched = new Set()) {
  const problems = [];
  const seen = new Set();
  for (const match of reportText.matchAll(/`([^`\n]+)`/g)) {
    const cited = match[1].trim();
    if (!isRepoPath(cited)) continue;
    // Deduped on the path, not on the citation: `path.mjs` and `path.mjs:12` are one
    // citation of one file, and a report that mentions a bad path five times with five
    // different line ranges has one problem to fix.
    const path = cited.replace(/:\d+(?:-\d+)?$/, '');
    if (seen.has(path)) continue;
    seen.add(path);
    if (existing.has(path) || touched.has(path)) continue;
    problems.push(
      `report cites \`${cited}\` and nothing at HEAD has that path, and ` +
        "the branch's diff neither adds nor deletes it — a citation a reviewer " +
        'cannot open reads as evidence and is not'
    );
  }
  return problems;
}

/**
 * Is this backtick content a repo path rather than a symbol, a script name or prose?
 *
 * Conservative on purpose, because a check that cries wolf is switched off. Two things have
 * to be true:
 *
 * 1. it contains a `/`, which is what distinguishes `example/src/App.tsx` from `App.tsx`,
 *    `test:native`, `hybridRef` or `fillWidth` — the bare-name cases are not the failure
 *    mode: an invented `Foo.kt` in a report is invisible either way, while an invented
 *    directory-qualified path is the thing a reviewer goes to read and cannot find.
 * 2. its last segment carries an extension. This is the part that took a real report to
 *    find: X4's own first line cites the branch as `task/X4-conformance`, which is
 *    repo-shaped, does not exist as a directory, and is not a mistake — a branch is written
 *    exactly like a path. Every citable file in this repo has an extension (`.mjs`, `.tsx`,
 *    `.kt`, `.md`, `.json`), so requiring one keeps the branch names and the occasional
 *    `origin/task/…` out, at the cost of not checking extensionless files (`LICENSE`) or
 *    directories, which a reader is not going to "open" and find missing anyway.
 *
 * A trailing line citation (`path.tsx:12-20`, the repo's own citation shape) is stripped
 * first, since it is a citation *of* a path.
 *
 * @param {string} cited the whole content of one backtick pair
 */
export function isRepoPath(cited) {
  if (cited.includes(' ') || cited.length === 0) return false;
  if (/^(https?:|@|https\/\/)/.test(cited)) return false;
  const path = cited.replace(/:\d+(?:-\d+)?$/, '');
  // No absolute paths and no `..`: a report cites the repo by its own layout, and a path
  // outside it is somebody's local machine, which `existing` can never contain.
  if (!path.includes('/') || path.startsWith('/')) return false;
  if (path.startsWith('~') || path.split('/').includes('..')) return false;
  if (!/^[\w.@-]+(\/[\w.@-]+)+$/.test(path)) return false;
  const leaf = path.slice(path.lastIndexOf('/') + 1);
  return leaf.includes('.') && !leaf.startsWith('.');
}

/**
 * The report's own gate table, against the lines `gate.mjs table` prints.
 *
 * Compared so a report cannot keep claiming a gate passed on a tree the report no longer
 * describes. Only the table *rows* are compared — a report is prose around them — and cells
 * are compared with inline-code markup stripped from their ends, because the ledger writes
 * ``| `check` |`` and a report may render `| check |`. Everything inside a cell, including
 * the numbers, must still agree exactly.
 *
 * @param {string} reportText
 * @param {string[]} generatedTable the lines `gate.mjs table` printed
 * @returns {string[]} problems
 */
export function reportTableProblems(reportText, generatedTable) {
  const inReport = reportRows(reportText);
  const generated = reportRows(generatedTable.join('\n'));
  if (generated.length === 0) {
    // Nothing recorded yet, so there is nothing to match: the `need` check already
    // refuses a round with no gates, and this one must not double-report it.
    return [];
  }
  if (inReport.length === 0) {
    return [
      'the report has no gate table, and `gate.mjs table` has one — paste ' +
        'the generated rows rather than typing results',
    ];
  }
  const problems = [];
  for (const row of generated) {
    // Compared on normalized cells, not raw text: `gate.mjs table` writes ``| `check` |``
    // and a report may render `| check |`. Which markup a gate name is wrapped in is
    // cosmetic; the numbers, the verdict and the code tree are what must agree exactly.
    if (inReport.some((line) => sameRow(line, row))) continue;
    const gate = unwrapGate(row.split('|')[1]?.trim() ?? row);
    const stale = inReport.find(
      (line) => unwrapGate(line.split('|')[1]?.trim() ?? '') === gate
    );
    problems.push(
      stale == null
        ? `the report's gate table has no row for \`${gate}\`, which ` +
            '`gate.mjs table` prints for this code tree'
        : `the report's row for \`${gate}\` does not match what ` +
            '`gate.mjs table` prints now — ' +
            `report says ${stale.trim()} and the ledger says ${row.trim()}. ` +
            'A stale row is a claim; the ledger row is evidence'
    );
  }

  // The same check in the other direction, because the loop above only proves the report is
  // not *missing* evidence. A row whose gate the ledger never printed is not stale, it is
  // invented: `gate.mjs table` prints one row per recorded run, so a gate nobody ran cannot
  // appear. Adding a `| real-input:ios | **PASS** | … |` row to a report whose iOS run never
  // happened passed every check — the loop walks generated rows, so the report's extra row
  // was never looked at, and a report is read as evidence.
  //
  // A row counts as a *gate claim* on two shapes rather than on which table it sits in,
  // because reports legitimately carry other tables whose first column names a gate (the
  // cost breakdown does). First cell gate-shaped — lower-case with colons, so `Button` and
  // prose are out — and second cell verdict-shaped, so the cost table's durations and a
  // coverage matrix's `covered` are out. A row that reads "this gate, this verdict" has to
  // have a run behind it.
  const known = new Set(
    generated.map((line) => gateNameOf(line) ?? '')
  );
  for (const row of inReport) {
    const gate = gateNameOf(row);
    if (gate == null || known.has(gate)) continue;
    problems.push(
      `the report's gate table has a row for \`${gate}\` and ` +
        '`gate.mjs table` prints none, so no run of that gate is recorded for this ' +
        `code tree — the row says ${row.trim()}. Paste the table, do not extend it`
    );
  }
  return problems;
}

/**
 * The gate a table row claims a result for, or null when it claims none.
 *
 * @param {string} row one markdown data row
 * @returns {string | null}
 */
function gateNameOf(row) {
  const cells = tableCells(row);
  if (cells.length < 2) return null;
  if (!/^[a-z][a-z0-9-]*(?::[A-Za-z0-9-]+)*$/.test(cells[0])) return null;
  if (!/^\*{0,2}(PASS|FAIL|green|red|stale|skipped|pending|missing|not run)\*{0,2}$/i.test(cells[1]))
    return null;
  return cells[0];
}

/**
 * A markdown row's cells, trimmed and with the markup that only decorates them removed.
 *
 * @param {string} row
 * @returns {string[]}
 */
function tableCells(row) {
  return row
    .split('|')
    .map((cell) => cell.trim().replace(/^`+|`+$/g, ''))
    .filter((cell) => cell !== '');
}

/**
 * Shorthand groups for `--only`, and the expander that applies them.
 *
 * `report` exists because the two report checks are never wanted apart — one reads the
 * report's citations, the other its gate table, and both need the file to exist. The
 * CONTRIBUTING example says `--only coverage,report`, so either that line or the person
 * typing it would otherwise be the bug.
 *
 * Expansion is deliberately *not* a whitelist: an unknown name comes back unchanged so the
 * caller's unknown-name check still fires and prints the real section names. Silently
 * dropping a typo is how a flag stops meaning anything.
 *
 * @type {Readonly<Record<string, ReadonlyArray<string>>>}
 */
export const ONLY_GROUPS = Object.freeze({
  report: Object.freeze(['report-paths', 'report-table']),
});

/**
 * @param {ReadonlyArray<string>} names as typed, comma-split and trimmed
 * @returns {string[]} every group replaced by its members, in order
 */
export function expandOnly(names) {
  return names.flatMap((name) => [...(ONLY_GROUPS[name] ?? [name])]);
}

/**
 * Are these two table rows the same row, ignoring inline code markup?
 *
 * @param {string} a
 * @param {string} b
 * @returns {boolean}
 */
function sameRow(a, b) {
  const left = tableCells(a);
  const right = tableCells(b);
  return left.length === right.length && left.every((c, i) => c === right[i]);
}

/**
 * The gate name out of a table cell, without the markup around it.
 *
 * `gate.mjs table` writes `` | `check` | … `` — backticks inside the cell — and the message
 * quotes the gate in backticks of its own, so passing the cell through produced
 * ``` ``check`` ``` in a terminal. Names are also matched across a report that chose
 * different markup than the ledger's, which is a cosmetic difference and not the mismatch
 * this function is looking for; the *rest of the row* is what has to agree exactly.
 *
 * @param {string} cell
 * @returns {string}
 */
function unwrapGate(cell) {
  return cell.replace(/^`+|`+$/g, '');
}

/**
 * The `| Gate | ... |` data rows of a markdown table.
 *
 * @param {string} text
 */
function reportRows(text) {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^\|\s*[^|-][^|]*\|.*\|\s*$/.test(line))
    .filter((line) => !/^\|\s*-{3,}/.test(line))
    .filter((line) => !/^\|\s*Gate\s*\|/i.test(line));
}

/**
 * Which report file a task id and a branch name refer to.
 *
 * AGENTS.md says the report is `docs/tasks/<ID>.report.md`, and `gate.mjs export --task <ID>`
 * writes its ledger to `docs/tasks/<ID>/gates.jsonl` — both keyed on the orchestrator's id.
 * But a branch is named for the *task*, not the id: X4's brief is `X4-conformance.md`, so its
 * branch is `task/X4-conformance` and the natural report name is
 * `docs/tasks/X4-conformance.report.md`, next to its own brief.
 *
 * Rather than pick one spelling and make the other a hard error, the command accepts either
 * and looks for both. What it will not do is run the report checks against a file that does
 * not exist, so it names the candidates it looked for.
 *
 * @param {string | null} id the orchestrator's task id (`X4`)
 * @param {string | null} branch the branch suffix (`X4-conformance`), or null
 * @returns {string[]} report paths to look for, in priority order
 */
export function reportCandidates(id, branch) {
  const names = [];
  if (branch != null && branch !== '') names.push(branch);
  if (id != null && id !== '' && !names.includes(id)) names.push(id);
  return names.map((name) => `docs/tasks/${name}.report.md`);
}

/**
 * Summarise the checks into the lines and exit code the command prints.
 *
 * Kept separate from the checks so a test can assert "these findings, these lines, this
 * code" without a git repository or a gate ledger.
 *
 * @param {Record<string, string[]>} sections name → problems
 * @returns {{lines: string[], ok: boolean}}
 */
export function summarise(sections) {
  const lines = [];
  let ok = true;
  for (const [name, problems] of Object.entries(sections)) {
    if (problems.length === 0) {
      lines.push(`  ok    ${name}`);
      continue;
    }
    ok = false;
    lines.push(`  ${String(problems.length)} problem(s)  ${name}`);
    for (const problem of problems) lines.push(`          - ${problem}`);
  }
  return { lines, ok };
}
