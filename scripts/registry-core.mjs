/**
 * One `REAL_INPUT_CONTROL_ROWS` row, in the shape the file already uses
 * (`id` / `title` / `screen`).
 *
 * Only used for a *new* row (an existing one is copied), and it wraps the title as a
 * concatenated string only when it would not fit in 80 columns - prettier's rule for
 * this file - so the generator's bytes and the formatter's bytes agree and
 * `bun run format` does not undo `bun run registry`.
 */
export function realInputRow(manifest) {
  const lines = ['  {', `    id: '${manifest.id}',`];
  const single = `    title: '${manifest.realInputTitle}',`;
  if (single.length <= 80) lines.push(single);
  else lines.push('    title:', `      '${manifest.realInputTitle}',`);
  lines.push(`    screen: '${manifest.exampleTab}',`, '  },');
  return lines;
}

