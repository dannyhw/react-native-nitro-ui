/**
 * Produce all generated output for a set of manifests, and check what the generator
 * does not write.
 *
 * Most files here carry more than one region (`example/src/App.tsx` carries four), so
 * regions are applied to a working copy that accumulates: rewriting each one from the
 * bytes on disk would let the last region of a file undo the ones before it. The
 * return value only reports a file when its final text differs from what is there, so
 * the drift check names exactly the lists that moved.
 *
 * @param {any[]} manifests
 * @param {(path: string) => string | null} readFile repo-relative; `null` for a
 *   file that does not exist.
 * @returns {{files: Record<string, string>, problems: string[], checked: string[]}}
 */
export function planRegistry(manifests, readFile) {
  const files = {};
  const problems = [];
  const checked = new Set();
  const original = new Map();
  const working = new Map();
  for (const spec of regionsFor(manifests)) {
    if (!working.has(spec.path)) {
      const current = readFile(spec.path);
      original.set(spec.path, current);
      working.set(spec.path, current);
      if (current == null) {
        problems.push(
          `${spec.path}: not found, but the registry writes into it`
        );
      }
    }
    const current = working.get(spec.path);
    if (current == null) continue;
    const result = replaceRegion(current, spec);
    problems.push(...result.problems);
    if (!result.found) continue;
    checked.add(spec.path);
    working.set(spec.path, result.content);
  }
  for (const [path, text] of working) {
    if (text != null && text !== original.get(path)) files[path] = text;
  }
  const sizingText = readFile(SIZING_TABLE_FILE);
  if (sizingText == null) {
    problems.push(
      `${SIZING_TABLE_FILE}: not found, but the registry writes it`
    );
  } else {
    checked.add(SIZING_TABLE_FILE);
    try {
      const sizing = sizingTableContent(
        manifests,
        parseJson(sizingText),
        sizingText
      );
      if (sizingText !== sizing) files[SIZING_TABLE_FILE] = sizing;
    } catch (error) {
      problems.push(error instanceof Error ? error.message : String(error));
    }
  }
  // The cross-checks - files something else owns, which a manifest has to agree with.
  // These are what turn a manifest from a note into a claim.
  //
  // Three of them run on the text this plan *produces*, for one reason each: `nitro.json`
  // and `example/src/App.tsx` because the generator writes them, and checking the bytes
  // on disk would report the entry/tab a new component's own `--write` is about to add
  // as missing - which would make `bun run registry` refuse to do the very job it is for.
  // `src/index.ts` is hand-written and nothing here writes it, so that one reads disk.
  problems.push(
    ...checkAutolinking(
      manifests,
      parseJson(working.get('nitro.json') ?? readFile('nitro.json')),
      // The stray-entry half reads the file as checked out: see checkAutolinking.
      parseJson(readFile('nitro.json'))
    )
  );
  problems.push(
    ...checkIndexExports(
      manifests,
      exportedComponents(readFile('src/index.ts'))
    )
  );
  problems.push(
    ...checkExampleScreens(
      manifests,
      working.get('example/src/App.tsx') ?? readFile('example/src/App.tsx'),
      readFile
    )
  );
  return { files, problems, checked: [...checked] };
}
