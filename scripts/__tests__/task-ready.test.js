/**
 * Guards for `scripts/task-ready-core.mjs` — the deciding half of `bun run task-ready`.
 *
 * The command itself shells out to `gen-registry.mjs` and `gate.mjs` and reads a git
 * repository, so the only part that can be asserted here is the part that decides: what
 * counts as a `TODO` in the wrong place, what counts as a cited path, and when a report's
 * table has stopped matching the ledger. That split is why the module exists — the same
 * reason `gate-core.mjs` and `lease-core.mjs` are separated from their CLIs.
 *
 * Each rule is shown red by mutating the function it guards; the mutations and the lines
 * that went red are in `docs/tasks/X4-conformance.report.md`.
 *
 * @file Unit gate: `check`.
 */

import { describe, expect, it } from '@jest/globals';

import {
  isRepoPath,
  missingReportPaths,
  reportCandidates,
  reportTableProblems,
  summarise,
  todoFindings,
} from '../task-ready-core.mjs';

/* --------------------------------- the TODO scan -------------------------------- */

describe('the TODO/FIXME scan', () => {
  /** One-file map, because every case is about one file's text. */
  const files = (path, text) => new Map([[path, text]]);

  const GENERATED =
    '// @generated by scripts/gen-registry.mjs (region: config-imports) - do not edit; run bun run regen';
  const END = '// @end-generated';

  it('is quiet on the clean case: a TODO in ordinary hand-written code', () => {
    // The whole shape of this check is a *narrow* one. A repo-wide TODO ban would report
    // existing notes nobody is touching, and the first person to hit that adds a flag that
    // turns the command off forever.
    expect(
      todoFindings(
        files(
          'src/components/Switch/Switch.tsx',
          '  // TODO: support a disabled tint on Android\n  return null;\n'
        )
      )
    ).toEqual([]);
  });

  it('goes red for a TODO inside a generated region', () => {
    const problems = todoFindings(
      files(
        'src/__tests__/viewConfigs.test.ts',
        [
          'const before = 1;',
          GENERATED,
          '// TODO: fold the host arm in here',
          END,
          'const after = 2;',
        ].join('\n')
      )
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('viewConfigs.test.ts:3');
    expect(problems[0]).toContain('the generator will overwrite');
  });

  it('goes red for a FIXME in a declared fallback table', () => {
    const problems = todoFindings(
      files(
        'ios/core/NitroUiDeclaredFallbacks.swift',
        '  "NitroUiSwitch": .init(width: 61, height: 28), // FIXME: measure on iPad\n'
      )
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('a declared fallback');
    expect(problems[0]).toContain('FIXME');
  });

  it('ends the region at the end marker, so a later TODO is not blamed on it', () => {
    // Without the end marker every line after the first region would be scanned, which
    // turns one real finding into a wall of them and hides the one that matters.
    expect(
      todoFindings(
        files(
          'bench/src/types.ts',
          [
            GENERATED,
            "export type ComponentName = 'Switch';",
            END,
            '// TODO: add the bench-only arms',
          ].join('\n')
        )
      )
    ).toEqual([]);
  });

  it('reports the line number a person can click, not the whole file', () => {
    const problems = todoFindings(
      files(
        'android/src/main/java/com/margelo/nitro/nitroui/core/NitroUiDeclaredFallbacks.kt',
        '\n\n\n// TODO: fourth line\n'
      )
    );
    expect(problems[0]).toMatch(/:4: \/\/ TODO/);
  });

  it('catches a TODO on the same line that opens a region', () => {
    // The marker and the payload can share a line in a compact table; a scanner that
    // flipped its flag *after* testing the line would let that one through.
    const problems = todoFindings(
      files(
        'src/__tests__/viewConfigs.test.ts',
        `${GENERATED} // TODO: tighten`
      )
    );
    expect(problems).toHaveLength(1);
  });
});

/* -------------------------------- the path scanner ------------------------------- */

describe('which backtick content counts as a repo path', () => {
  it('accepts the shapes a report actually uses', () => {
    for (const cited of [
      'example/src/App.tsx',
      'scripts/real-input/a11y.mjs',
      'docs/tasks/X4/gates.jsonl',
      'example/__tests__/Conformance.harness.tsx',
    ]) {
      expect(isRepoPath(cited)).toBe(true);
    }
  });

  it('declines a top-level file, because a bare name cannot be resolved without guessing', () => {
    // `nitro-ui.sizing.json` and `package.json` do exist, but so do plenty of bare names
    // that do not, and the check's value is in never crying wolf on prose.
    expect(isRepoPath('nitro-ui.sizing.json')).toBe(false);
    expect(isRepoPath('package.json')).toBe(false);
  });

  it("accepts a path with a line citation, the repo's own shape", () => {
    expect(isRepoPath('Button.harness.tsx:283-290')).toBe(false);
    expect(isRepoPath('example/__tests__/Button.harness.tsx:283-290')).toBe(
      true
    );
  });

  it('rejects symbols, script names, and prose', () => {
    for (const cited of [
      'hybridRef',
      'fillWidth',
      'test:native',
      'check',
      'gate.mjs need --for review',
      'npm run check',
      'HybridNitroUiSwitch',
      '',
    ]) {
      expect(isRepoPath(cited)).toBe(false);
    }
  });

  it('rejects anything outside the repo', () => {
    for (const cited of [
      '/Users/someone/other/thing.ts',
      '~/scratch/file.ts',
      '../outside/file.ts',
      'src/../secrets/env.ts',
      '@react-native-harness/ui',
      'https://example.com/a/b',
    ]) {
      expect(isRepoPath(cited)).toBe(false);
    }
  });
});

describe('report citations that point at nothing', () => {
  const existing = new Set([
    'scripts/conformance-core.mjs',
    'example/__tests__/Conformance.harness.tsx',
  ]);

  it('is quiet when every cited path exists', () => {
    expect(
      missingReportPaths(
        'Rules live in `scripts/conformance-core.mjs`; the fixtures are in ' +
          '`example/__tests__/Conformance.harness.tsx` and the word `coverage`.',
        existing
      )
    ).toEqual([]);
  });

  it('goes red for a path that is not in the tree, and quotes it', () => {
    const problems = missingReportPaths(
      'See `scripts/conformance/measure-a11y.mjs` for the numbers.',
      existing
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('scripts/conformance/measure-a11y.mjs');
    expect(problems[0]).toContain('cannot open');
  });

  it('allows a path the branch itself adds or deletes', () => {
    // A report describes work in this branch, so citing a file the diff creates (or
    // removes) is the normal case, not an invented reference.
    expect(
      missingReportPaths(
        'New: `scripts/real-input/a11y-sweep.mjs`. Removed: `scripts/conformance/measure-a11y.mjs`.',
        existing,
        new Set([
          'scripts/real-input/a11y-sweep.mjs',
          'scripts/conformance/measure-a11y.mjs',
        ])
      )
    ).toEqual([]);
  });

  it('reports each distinct bad path once, however often it appears', () => {
    expect(
      missingReportPaths(
        '`scripts/nope.mjs` then `scripts/nope.mjs:12` again.',
        existing
      )
    ).toHaveLength(1);
  });

  it('ignores a bare file name, which no check can resolve', () => {
    expect(missingReportPaths('See `REPORT-TEMPLATE.md`.', existing)).toEqual(
      []
    );
  });
});

/* ---------------------------------- the gate table -------------------------------- */

describe("the report's gate table against the ledger", () => {
  const generated = [
    '| Gate | Result | Tree | Notes |',
    '| --- | --- | --- | --- |',
    '| check | PASS | `abc1234` | 41 s |',
    '| harness:ios | PASS | `abc1234` | 3 m 12 s |',
  ];

  it('is quiet when the report pasted the generated rows', () => {
    const report = [
      '## Gates',
      '',
      '| Gate | Result | Tree | Notes |',
      '| --- | --- | --- | --- |',
      generated[2],
      generated[3],
      '',
      'Some prose after.',
    ].join('\n');
    expect(reportTableProblems(report, generated)).toEqual([]);
  });

  it('goes red when a row was retyped with different text', () => {
    const report = [
      '| Gate | Result | Tree | Notes |',
      '| --- | --- | --- | --- |',
      '| check | PASS | `abc1234` | 41 s |',
      '| harness:ios | PASS | `deadbee` | felt fast |',
    ].join('\n');
    const problems = reportTableProblems(report, generated);
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('harness:ios');
    expect(problems[0]).toContain('A stale row is a claim');
  });

  it('goes red when the report simply left a gate out', () => {
    const report = ['| Gate | Result |', '| --- | --- |', generated[2]].join(
      '\n'
    );
    expect(reportTableProblems(report, generated).join('\n')).toContain(
      'no row for `harness:ios`'
    );
  });

  it('goes red when the report has no table at all', () => {
    expect(
      reportTableProblems(
        '## Gates\n\nEverything passed, I promise.\n',
        generated
      )[0]
    ).toContain('no gate table');
  });

  it('says nothing when the ledger has no rows yet — `need` already refuses that', () => {
    // Reporting it twice would make the missing gates look like two different problems.
    expect(
      reportTableProblems('## Gates\n\n| Gate | X |\n| --- | --- |\n', [])
    ).toEqual([]);
  });

  it('compares the whole row, so a different code tree cannot pass as the same gate', () => {
    const report = '| harness:ios | PASS | `abc1234` | 3 m 12 s |';
    const moved = generated.map((line) =>
      line === report ? '| harness:ios | STALE | `abc9999` | 3 m 12 s |' : line
    );
    expect(reportTableProblems(report, moved).join('\n')).toContain('STALE');
  });
});

/* ------------------------------------ the id -------------------------------------- */

describe('which report file a task refers to', () => {
  it('prefers the branch-named report, since that is where the brief lives', () => {
    expect(reportCandidates('X4', 'X4-conformance')).toEqual([
      'docs/tasks/X4-conformance.report.md',
      'docs/tasks/X4.report.md',
    ]);
  });

  it('still checks the bare id when there is no branch suffix to go on', () => {
    expect(reportCandidates('X4', null)).toEqual(['docs/tasks/X4.report.md']);
    expect(reportCandidates('X4', '')).toEqual(['docs/tasks/X4.report.md']);
  });

  it('does not ask for the same file twice', () => {
    expect(reportCandidates('X4', 'X4')).toEqual(['docs/tasks/X4.report.md']);
  });
});

/* ----------------------------------- summarise ------------------------------------ */

describe('the summary the command prints', () => {
  it('passes when every section is empty', () => {
    const { lines, ok } = summarise({ registry: [], coverage: [] });
    expect(ok).toBe(true);
    expect(lines).toEqual(['  ok    registry', '  ok    coverage']);
  });

  it('fails on one problem, and indents it under its section', () => {
    const { lines, ok } = summarise({
      registry: [],
      coverage: ['Switch has no fixture'],
    });
    expect(ok).toBe(false);
    expect(lines).toEqual([
      '  ok    registry',
      '  1 problem(s)  coverage',
      '          - Switch has no fixture',
    ]);
  });

  it('reports every section that has problems, not just the first', () => {
    // The command exists so a round hands in once; bailing at the first failure would send
    // the person back three times for three known problems.
    const { lines, ok } = summarise({
      a: ['one'],
      b: [],
      c: ['two', 'three'],
    });
    expect(ok).toBe(false);
    expect(lines.filter((line) => line.includes('problem(s)'))).toEqual([
      '  1 problem(s)  a',
      '  2 problem(s)  c',
    ]);
    expect(lines.filter((line) => line.trim().startsWith('-'))).toHaveLength(3);
  });

  it('says nothing for no sections, rather than claiming a pass on nothing', () => {
    const { lines, ok } = summarise({});
    expect(lines).toEqual([]);
    // Vacuously ok: the command itself refuses an empty section list by construction, so
    // the flag is not the interesting part here — printing nothing is.
    expect(ok).toBe(true);
  });
});
