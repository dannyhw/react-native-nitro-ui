describe('the TODO/FIXME scan', () => {
  const files = (path, text) => new Map([[path, text]]);

  const GENERATED =
    '// @generated by scripts/gen-registry.mjs (region: config-imports) - do not edit; run bun run regen';
  const END = '// @end-generated';

  it('is quiet on the clean case: a TODO in ordinary hand-written code', () => {
    expect(
      todoFindings(
        files(
          'src/components/Switch/Switch.tsx',
          '  // TODO: support a disabled tint on Android\n  return null;\n'
        )
      )
    ).toEqual([]);
  });

  it('goes red for a TODO inside a generated region', () => {
    const problems = todoFindings(
      files(
        'src/__tests__/viewConfigs.test.ts',
        [
          'const before = 1;',
          GENERATED,
          '// TODO: fold the host arm in here',
          END,
          'const after = 2;',
        ].join('\n')
      )
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('viewConfigs.test.ts:3');
    expect(problems[0]).toContain('the generator will overwrite');
  });

  it('goes red for a FIXME in a declared fallback table', () => {
    const problems = todoFindings(
      files(
        'ios/core/NitroUiDeclaredFallbacks.swift',
        '  "NitroUiSwitch": .init(width: 61, height: 28), // FIXME: measure on iPad\n'
      )
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('a declared fallback');
    expect(problems[0]).toContain('FIXME');
  });

  it('goes red for a TODO beside the fallback number in a component source', () => {
    const swift = [
      '  /// The size the control reports before it has measured anything.',
      '  // TODO: re-measure on iPad before shipping',
      '  private static let fallbackSize = (width: 61.0, height: 29.0)',
      '',
      '  private static let somethingElse = 3.0',
      '',
      '  // TODO: this is fine, it is about something else entirely',
    ].join('\n');
    const problems = todoFindings(
      files('ios/components/Switch/HybridNitroUiSwitch.swift', swift)
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('HybridNitroUiSwitch.swift:2');
    expect(problems[0]).toContain('a fallback number');
  });

  it('goes red for a FIXME beside the Kotlin fallback constants', () => {
    const kotlin = [
      '  companion object {',
      '    private const val FALLBACK_WIDTH_DP = 52.0',
      '    // FIXME: 48 is the touch target, not the track',
      '    private const val FALLBACK_HEIGHT_DP = 48.0',
      '  }',
    ].join('\n');
    const problems = todoFindings(
      files(
        'android/src/main/java/com/margelo/nitro/nitroui/HybridNitroUiSwitch.kt',
        kotlin
      )
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('HybridNitroUiSwitch.kt:3');
    expect(problems[0]).toContain('FIXME');
  });

  it('still leaves a note alone two lines past the fallback declaration', () => {
    const swift = [
      '  private static let fallbackSize = (width: 61.0, height: 29.0)',
      '  private static let otherThing = 1.0',
      '  private static let third = 2.0',
      '  // TODO: nothing to do with the fallback',
    ].join('\n');
    expect(
      todoFindings(
        files('ios/components/Button/HybridNitroUiButton.swift', swift)
      )
    ).toEqual([]);
  });

  it('calls a hit inside a generated region the generator problem, not a fallback one', () => {
    const problems = todoFindings(
      files(
        'NitroUiDeclaredFallbacks.swift',
        [GENERATED, '// TODO: comes from the manifest', END].join('\n')
      )
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('a generated region');
  });

  it('ends the region at the end marker, so a later TODO is not blamed on it', () => {
    expect(
      todoFindings(
        files(
          'bench/src/types.ts',
          [
            GENERATED,
            "export type ComponentName = 'Switch';",
            END,
            '// TODO: add the bench-only arms',
          ].join('\n')
        )
      )
    ).toEqual([]);
  });

  it('reports the line number a person can click, not the whole file', () => {
    const problems = todoFindings(
      files(
        'android/src/main/java/com/margelo/nitro/nitroui/core/NitroUiDeclaredFallbacks.kt',
        '\n\n\n// TODO: fourth line\n'
      )
    );
    expect(problems[0]).toMatch(/:4: \/\/ TODO/);
  });

  it('catches a TODO on the same line that opens a region', () => {
    const problems = todoFindings(
      files(
        'src/__tests__/viewConfigs.test.ts',
        `${GENERATED} // TODO: tighten`
      )
    );
    expect(problems).toHaveLength(1);
  });
});

