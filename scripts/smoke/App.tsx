import {
  Button,
  ButtonGroup,
  Checkbox,
  Chip,
  DatePicker,
  Host,
  IconButton,
  Menu,
  type MenuGroup,
  nitroUiCore,
  Picker,
  Progress,
  SearchField,
  SegmentedControl,
  Slider,
  ListItem,
  Stepper,
  Switch,
  TextField,
} from 'react-native-nitro-ui';
import * as React from 'react';
import {
  ScrollView,
  StyleSheet,
  Text,
  View,
  type LayoutChangeEvent,
} from 'react-native';

// Consumer smoke app: the smoke scripts copy this file over a generated app's
// App.tsx. It renders every exported component once and logs
// `NITRO_UI_SMOKE_READY <control>=<W>x<H> …` when the native core has answered and
// every control has a non-zero box, which `scripts/smoke/lib.mjs` asserts.

type SmokeStatus = 'starting' | 'ready' | 'layout' | 'error';

const SMOKE_MENU_GROUP: MenuGroup = {
  actions: [
    { id: 'one', title: 'One' },
    { id: 'two', title: 'Two' },
  ],
};

/**
 * Also listed in `scripts/smoke/lib.mjs`, because this file is copied into a
 * generated app and cannot import that module.
 */
const SMOKE_CONTROLS = [
  // @generated by scripts/gen-registry.mjs (region: smoke-controls) - do not edit; run bun run regen
  'switch',
  'slider',
  'button',
  'progress',
  'segmented-control',
  'date-picker',
  'picker',
  'menu',
  'text-field',
  'chip',
  'checkbox',
  'search-field',
  'icon-button',
  'button-group',
  'stepper',
  'list-item',
  // @end-generated
  // The container: its hosted children report no box of their own.
  'host',
] as const;

type SmokeControl = (typeof SMOKE_CONTROLS)[number];

/** Module-level: a literal in the JSX would be a fresh identity on every render. */
const SMOKE_BUTTON_GROUP_ITEMS = [
  { id: 'copy', title: 'Copy' },
  { id: 'cut', title: 'Cut' },
  { id: 'paste', title: 'Paste' },
];

const READY_PREFIX = 'NITRO_UI_SMOKE_READY';
const PENDING_PREFIX = 'NITRO_UI_SMOKE_PENDING';

/** How long to wait for every box once the core answered. */
const LAYOUT_TIMEOUT_MS = 6000;

interface Box {
  width: number;
  height: number;
}

function boxText(box: Box | undefined): string {
  return box == null ? 'never' : `${box.width}x${box.height}`;
}

function isLaidOut(box: Box | undefined): boolean {
  return box != null && box.width > 0 && box.height > 0;
}

function boxesText(boxes: Partial<Record<SmokeControl, Box>>): string {
  return SMOKE_CONTROLS.map(
    (control) => `${control}=${boxText(boxes[control])}`
  ).join(' ');
}

export default function App(): React.ReactElement {
  const [status, setStatus] = React.useState<SmokeStatus>('starting');
  const [coreNow, setCoreNow] = React.useState<number | null>(null);
  const [boxes, setBoxes] = React.useState<Partial<Record<SmokeControl, Box>>>(
    {}
  );
  const announcedReady = React.useRef(false);
  const announcedPending = React.useRef(false);

  React.useEffect(() => {
    if (status !== 'starting') {
      return;
    }
    try {
      // Proves NitroModules + our native core are linked and callable.
      const now = nitroUiCore.now();
      console.log(`NITRO_UI_SMOKE_CORE_NOW=${now}`);
      setCoreNow(now);
      setStatus('ready');
    } catch (error) {
      console.log(`NITRO_UI_SMOKE_ERROR=${String(error)}`);
      setStatus('error');
    }
  }, [status]);

  /** `onLayout` per control, with a stable handler each. */
  const measureFor = React.useMemo(() => {
    const handlers = new Map<
      SmokeControl,
      (event: LayoutChangeEvent) => void
    >();
    return (control: SmokeControl) => {
      let handler = handlers.get(control);
      if (handler == null) {
        handler = (event: LayoutChangeEvent) => {
          const { width, height } = event.nativeEvent.layout;
          setBoxes((current) => {
            const previous = current[control];
            if (
              previous != null &&
              previous.width === width &&
              previous.height === height
            ) {
              return current;
            }
            return { ...current, [control]: { width, height } };
          });
        };
        handlers.set(control, handler);
      }
      return handler;
    };
  }, []);

  // The ready line, once: core answered, and every control has a non-zero box.
  React.useEffect(() => {
    if (status !== 'ready' || announcedReady.current) {
      return;
    }
    if (!SMOKE_CONTROLS.every((control) => isLaidOut(boxes[control]))) {
      return;
    }
    announcedReady.current = true;
    console.log(`${READY_PREFIX} ${boxesText(boxes)}`);
  }, [status, boxes]);

  // Says what is missing instead of staying quiet until the runner's timeout.
  React.useEffect(() => {
    if (status !== 'ready' || announcedPending.current) {
      return;
    }
    if (SMOKE_CONTROLS.every((control) => isLaidOut(boxes[control]))) {
      return;
    }
    const timer = setTimeout(() => {
      if (announcedPending.current || announcedReady.current) {
        return;
      }
      announcedPending.current = true;
      console.log(`${PENDING_PREFIX} ${boxesText(boxes)}`);
      setStatus('layout');
    }, LAYOUT_TIMEOUT_MS);
    return () => {
      clearTimeout(timer);
    };
  }, [status, boxes]);

  const missing = SMOKE_CONTROLS.filter(
    (control) => !isLaidOut(boxes[control])
  );

  return (
    <View testID="SMOKE-root" style={[StyleSheet.absoluteFill, styles[status]]}>
      <ScrollView contentContainerStyle={styles.container}>
        <Text testID="SMOKE-nitro-ui-core">
          NitroUiCore.now(): {coreNow == null ? 'pending' : coreNow}
        </Text>
        <Text style={styles.layoutText} testID="SMOKE-layouts">
          {status === 'layout'
            ? `waiting for a box: ${missing.join(', ')}`
            : 'layout'}
          {'\n'}
          {SMOKE_CONTROLS.map((control) => (
            <React.Fragment key={control}>
              {control} {boxText(boxes[control])}
              {'\n'}
            </React.Fragment>
          ))}
        </Text>

        {/* One line per exported component. The `onLayout` is what the ready
            line reports. */}
        <Switch
          defaultValue={true}
          onLayout={measureFor('switch')}
          testID="SMOKE-switch"
        />
        <Slider
          defaultValue={0.5}
          onLayout={measureFor('slider')}
          testID="SMOKE-slider"
        />
        <Button
          onLayout={measureFor('button')}
          title="Save"
          testID="SMOKE-button"
        />
        <Progress
          onLayout={measureFor('progress')}
          testID="SMOKE-progress"
          value={0.6}
        />
        <SegmentedControl
          onLayout={measureFor('segmented-control')}
          options={['One', 'Two', 'Three']}
          testID="SMOKE-segmented-control"
        />
        <DatePicker
          onLayout={measureFor('date-picker')}
          testID="SMOKE-date-picker"
        />
        <Picker
          onLayout={measureFor('picker')}
          options={['One', 'Two', 'Three']}
          testID="SMOKE-picker"
        />
        <Menu
          onLayout={measureFor('menu')}
          title="Actions"
          group={SMOKE_MENU_GROUP}
          testID="SMOKE-menu"
        />
        <TextField
          onLayout={measureFor('text-field')}
          placeholder="Name"
          testID="SMOKE-text-field"
        />
        <SearchField
          onLayout={measureFor('search-field')}
          placeholder="Search"
          testID="SMOKE-search-field"
        />
        <Chip
          onLayout={measureFor('chip')}
          label="Filter"
          testID="SMOKE-chip"
        />
        <Checkbox
          onLayout={measureFor('checkbox')}
          label="Accept"
          testID="SMOKE-checkbox"
        />
        {/* The drawable-name form of `androidIcon` needs no dev server, so it
            also works in a release bundle. */}
        <IconButton
          accessibilityLabel="Search"
          androidIcon="nitroui_search"
          onLayout={measureFor('icon-button')}
          systemImage="magnifyingglass"
          testID="SMOKE-icon-button"
        />
        {/* One node on both platforms, so one `onLayout` covers the control. */}
        <Stepper
          accessibilityLabel="Quantity"
          onLayout={measureFor('stepper')}
          testID="SMOKE-stepper"
        />
        {/* `fillWidth`: the box is the row's own height at the screen's width. */}
        <ButtonGroup
          accessibilityLabel="Editing commands"
          items={SMOKE_BUTTON_GROUP_ITEMS}
          testID="SMOKE-button-group"
          onLayout={measureFor('button-group')}
        />
        {/* `fillWidth`, like the ButtonGroup above. */}
        <ListItem
          accessibilityLabel="Notifications"
          onLayout={measureFor('list-item')}
          testID="SMOKE-list-item"
          title="Notifications"
          value="On"
        />
        {/* One Host, two hosted Switches: on Android they share one Compose
            composition, on iOS the Host is a plain View. The Host needs a
            height of its own. */}
        <Host
          onLayout={measureFor('host')}
          style={styles.host}
          testID="SMOKE-host"
        >
          <Switch defaultValue={true} testID="SMOKE-host-switch-a" />
          <Switch defaultValue={false} testID="SMOKE-host-switch-b" />
        </Host>
      </ScrollView>
    </View>
  );
}

const styles = StyleSheet.create({
  container: {
    alignItems: 'center',
    gap: 12,
    padding: 24,
    // Stay clear of the iOS status bar / notch in screenshots.
    paddingTop: 60,
  },
  host: {
    // Two Switches, one row each: say how tall the Host is.
    height: 96,
    alignSelf: 'stretch',
  },
  layoutText: {
    fontSize: 11,
    opacity: 0.8,
  },
  starting: {
    backgroundColor: '#ffffff',
  },
  ready: {
    backgroundColor: '#ff0000',
  },
  layout: {
    backgroundColor: '#ff9500',
  },
  error: {
    backgroundColor: '#0000ff',
  },
});
