import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from '@jest/globals';

import { NitroUiButtonConfig } from '../components/Button/NitroUiButtonConfig';
import { NitroUiProgressConfig } from '../components/Progress/NitroUiProgressConfig';
import { NitroUiSliderConfig } from '../components/Slider/NitroUiSliderConfig';
import { NitroUiSwitchConfig } from '../components/Switch/NitroUiSwitchConfig';

const generatedDir = join(
  __dirname,
  '..',
  '..',
  'nitrogen',
  'generated',
  'shared',
  'json'
);

/**
 * Every hand-written copy of a generated view config, keyed by the file name
 * nitrogen writes it to.
 */
const copies: Record<string, unknown> = {
  'NitroUiButtonConfig.json': NitroUiButtonConfig,
  'NitroUiProgressConfig.json': NitroUiProgressConfig,
  'NitroUiSliderConfig.json': NitroUiSliderConfig,
  'NitroUiSwitchConfig.json': NitroUiSwitchConfig,
};

describe('hand-written view configs', () => {
  it('are all still generated by nitrogen', () => {
    expect(existsSync(generatedDir)).toBe(true);
  });

  it.each(Object.keys(copies))('%s matches nitrogen output', (fileName) => {
    const generated = JSON.parse(
      readFileSync(join(generatedDir, fileName), 'utf8')
    );
    expect(copies[fileName]).toEqual(generated);
  });

  it('covers every generated config (add the copy + an entry here)', () => {
    const generated = readdirSync(generatedDir).filter((file) =>
      file.endsWith('Config.json')
    );
    expect(Object.keys(copies).sort()).toEqual(generated.sort());
  });
});
